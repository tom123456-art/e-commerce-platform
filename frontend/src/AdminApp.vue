  【涉及的核心知识点】
    - ref()：响应式数据绑定
    - onMounted()：组件挂载后的生命周期钩子
    - async/await：异步数据获取
    - 组件间数据传递与状态管理
-->
<script>
/**
 * ============================================================================
 * 脚本部分：AdminApp.vue 组件逻辑
 * ============================================================================
 *
 * 【教学知识点：无逻辑组件】
 *
 * AdminApp.vue 是一个"无逻辑组件"（也称为"透传组件"）：
 * - 不包含任何业务逻辑
 * - 不定义任何状态
 * - 不引入任何依赖
 * - 仅作为路由的入口点
 *
 * 这种组件存在的原因：
 * 1. Vue 应用必须有一个根组件
 * 2. 不同的构建目标（用户端 vs 管理后台）需要不同的根组件
 * 3. 可以在需要时扩展功能（如添加全局错误处理）
 *
 * 【教学知识点：组件最小化原则】
 *
 * 组件应该尽量保持简单：
 * - 单一职责：每个组件只负责一件事
 * - 最小知识：组件只依赖它需要的东西
 * - 易于测试：简单的组件更容易测试
 *
 * AdminApp.vue 遵循了这些原则：
 * - 职责：仅作为路由入口
 * - 依赖：无
 * - 测试：无需测试（没有逻辑）
 */
