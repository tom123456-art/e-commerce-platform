<template>
  <!--
    ============================================================================
    模板部分：AdminApp.vue 管理后台主应用组件
    ============================================================================

    【教学知识点：极简根组件】

    管理后台的根组件非常简单，只有一个 <router-view />。
    这是因为管理后台的布局（导航栏、侧边栏等）由 AdminLayout.vue 负责。

    【教学知识点：组件职责划分】

    本项目的组件职责划分：
    - App.vue: 用户端根组件，包含导航栏和布局
    - AdminApp.vue: 管理后台根组件，仅作为路由出口
    - AdminLayout.vue: 管理后台布局组件，包含侧边栏和导航

    为什么管理后台不直接在 AdminApp.vue 中写布局？
    1. 灵活性：登录页面不需要管理后台的布局
    2. 代码分离：布局逻辑与应用入口分离
    3. 路由结构：登录页面在 AdminLayout 之外

    【教学知识点：路由配置与组件对应关系】

    管理后台的路由配置：
    - /login → LoginView.vue（不在 AdminLayout 内）
    - / → AdminLayout.vue（父组件）
      - / → AdminDashboardView.vue（子组件）
      - /users → AdminUsersView.vue（子组件）
      - ...

    AdminApp.vue 中的 <router-view /> 会渲染：
    - 访问 /login → LoginView.vue
    - 访问 / → AdminLayout.vue（AdminLayout 内有另一个 <router-view /> 渲染子组件）
  -->
  <router-view />
</template>

